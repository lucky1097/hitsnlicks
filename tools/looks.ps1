# Builds js/looks.js from the character layer folders in assets/postava (the browser can't list folders).
# Run after adding layers; tools/publish.ps1 runs it too.
# A file named base_*.png (anywhere) is the base everything is drawn on; every other PNG is one option of its folder.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$dir = Join-Path $root 'assets\postava'
$enc = New-Object Text.UTF8Encoding($false)

# drawing order (bottom to top), names shown in the game, and whether "nothing" is a valid choice
$parts = @(
  @{ id = 'zaklad';   name = 'Telo';       optional = $false },
  @{ id = 'plet';     name = 'Pleť';       optional = $false },
  @{ id = 'nos';      name = 'Nos';        optional = $false },
  # brows under the eyes: the eye layer wins where both touch (no doubled lids)
  @{ id = 'obocie';   name = 'Obočie';     optional = $false },
  @{ id = 'oci';      name = 'Oči';        optional = $false },
  @{ id = 'usta';     name = 'Ústa';       optional = $false },
  @{ id = 'brada';    name = 'Brada';      optional = $true },
  @{ id = 'ucesy';    name = 'Účes';       optional = $false },
  @{ id = 'na_hlave'; name = 'Na hlave';   optional = $true },
  @{ id = 'okuliare'; name = 'Okuliare';   optional = $true },
  @{ id = 'doplnky';  name = 'Doplnky';    optional = $true }
)

$rel = { param($f) 'assets/postava/' + $f.FullName.Substring($dir.Length + 1).Replace('\', '/') }
$base = Get-ChildItem $dir -Recurse -File -Filter 'base_*.png' | Select-Object -First 1
$out = New-Object Text.StringBuilder
[void]$out.AppendLine('// Generated by tools/looks.ps1 from assets/postava. Do not edit by hand: add PNG layers and run the script.')
[void]$out.AppendLine('export const LOOK_BASE = ' + $(if ($base) { "'" + (& $rel $base) + "'" } else { 'null' }) + ';')
[void]$out.AppendLine('export const LOOK_PARTS = [')
foreach ($p in $parts) {
  $files = Get-ChildItem (Join-Path $dir $p.id) -Recurse -File -Filter '*.png' -ErrorAction SilentlyContinue | Where-Object { $_.Name -notlike 'base_*' } | Sort-Object Name
  if (-not $files) { continue }
  $items = $files | ForEach-Object {
    $id = $_.BaseName
    # "hair_01_buzz_fade" -> "buzz fade"
    $label = ($id -replace '^[a-z]+_\d+_', '' -replace '^\d+_', '' -replace '_', ' ')
    "    { id: '$id', name: '$label', src: '$(& $rel $_)' },"
  }
  [void]$out.AppendLine("  { id: '$($p.id)', name: '$($p.name)', optional: $($p.optional.ToString().ToLower()), items: [")
  $items | ForEach-Object { [void]$out.AppendLine($_) }
  [void]$out.AppendLine('  ] },')
}
[void]$out.AppendLine('];')
[IO.File]::WriteAllText((Join-Path $root 'js\looks.js'), $out.ToString(), $enc)
'looks.js: ' + ((Get-ChildItem $dir -Recurse -File -Filter '*.png').Count) + ' png'
