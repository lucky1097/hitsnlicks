# Builds js/looks.js from the character layer folders in assets/postava (the browser can't list folders).
# Run after adding layers; tools/publish.ps1 runs it too.
# A file named base_*.png (anywhere) is the base everything is drawn on; every other PNG is one option of its folder.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$dir = Join-Path $root 'assets\postava'
$enc = New-Object Text.UTF8Encoding($false)

# drawing order (bottom to top), names shown in the game, and whether "nothing" is a valid choice
$parts = @(
  @{ id = 'zaklad';   name = 'Telo';       optional = $false },
  @{ id = 'plet';     name = 'Pleť';       optional = $false },
  # neck things first: a long beard falls over the tattoo and the chain
  @{ id = 'tetovanie'; name = 'Tetovanie'; optional = $true },
  @{ id = 'retiazka'; name = 'Retiazka';   optional = $true },
  @{ id = 'nos';      name = 'Nos';        optional = $false },
  # brows under the eyes: the eye layer wins where both touch (no doubled lids)
  @{ id = 'obocie';   name = 'Obočie';     optional = $false },
  @{ id = 'oci';      name = 'Oči';        optional = $false },
  @{ id = 'usta';     name = 'Ústa';       optional = $false },
  @{ id = 'brada';    name = 'Brada';      optional = $true },
  # earrings under the hair: dreads and twists cover them
  @{ id = 'nausnice'; name = 'Náušnice';   optional = $true },
  @{ id = 'ucesy';    name = 'Účes';       optional = $false },
  @{ id = 'na_hlave'; name = 'Na hlave';   optional = $true },
  @{ id = 'okuliare'; name = 'Okuliare';   optional = $true },
  @{ id = 'doplnky';  name = 'Extra';      optional = $true }
)

# ?v= from the file content, so a phone never shows an old cached layer
$rel = { param($f) 'assets/postava/' + $f.FullName.Substring($dir.Length + 1).Replace('\', '/') + '?v=' + (Get-FileHash $f.FullName -Algorithm MD5).Hash.Substring(0, 8).ToLower() }
$base = Get-ChildItem $dir -Recurse -File -Filter 'base_*.png' | Select-Object -First 1
# Headwear hides the hair above its lower edge: for each hat, the lowest opaque pixel per column (33 points,
# in % of the canvas) becomes a clip-path for the hair layer. Headbands (bandana) don't hide anything.
if (-not ('HatProfile' -as [type])) {
  Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition @'
using System; using System.Drawing; using System.Drawing.Imaging; using System.Runtime.InteropServices;
public static class HatProfile {
  public static double[] Of(string path, int n) {
    using (var src = new Bitmap(path)) using (var bmp = new Bitmap(src.Width, src.Height, PixelFormat.Format32bppArgb)) {
      using (var g = Graphics.FromImage(bmp)) g.DrawImage(src, 0, 0, src.Width, src.Height);
      int w = bmp.Width, h = bmp.Height; var d = new int[w * h];
      var bd = bmp.LockBits(new Rectangle(0, 0, w, h), ImageLockMode.ReadOnly, PixelFormat.Format32bppArgb);
      Marshal.Copy(bd.Scan0, d, 0, d.Length); bmp.UnlockBits(bd);
      var low = new int[w]; int x0 = w, x1 = -1;
      for (int x = 0; x < w; x++) { low[x] = -1; for (int y = h - 1; y >= 0; y--) if (((d[y * w + x] >> 24) & 255) > 128) { low[x] = y; break; } if (low[x] >= 0) { x0 = Math.Min(x0, x); x1 = Math.Max(x1, x); } }
      var o = new double[n];
      for (int i = 0; i < n; i++) {
        int x = (int)Math.Round(i * (w - 1) / (double)(n - 1));
        int cx = Math.Max(x0, Math.Min(x1, x)); // outside the hat: its outermost edge
        int best = -1; for (int k = Math.Max(x0, cx - 6); k <= Math.Min(x1, cx + 6); k++) best = Math.Max(best, low[k]);
        o[i] = Math.Round(100.0 * (best + 2) / h, 1);
      }
      return o;
    }
  }
}
'@
}
$hatClip = @{}
Get-ChildItem (Join-Path $dir 'na_hlave') -Filter *.png -ErrorAction SilentlyContinue | Where-Object { $_.BaseName -notmatch 'bandana' } | ForEach-Object {
  $hatClip[$_.BaseName] = ([HatProfile]::Of($_.FullName, 33) | ForEach-Object { $_.ToString([Globalization.CultureInfo]::InvariantCulture) }) -join ','
}

$out = New-Object Text.StringBuilder
[void]$out.AppendLine('// Generated by tools/looks.ps1 from assets/postava. Do not edit by hand: add PNG layers and run the script.')
[void]$out.AppendLine('export const LOOK_BASE = ' + $(if ($base) { "'" + (& $rel $base) + "'" } else { 'null' }) + ';')
[void]$out.AppendLine('export const LOOK_PARTS = [')
foreach ($p in $parts) {
  $files = Get-ChildItem (Join-Path $dir $p.id) -Recurse -File -Filter '*.png' -ErrorAction SilentlyContinue | Where-Object { $_.Name -notlike 'base_*' } | Sort-Object Name
  if (-not $files) { continue }
  $items = $files | ForEach-Object {
    $id = $_.BaseName
    # "hair_01_buzz_fade" -> "buzz fade"
    $label = ($id -replace '^[a-z]+_\d+_', '' -replace '^\d+_', '' -replace '_', ' ')
    $clip = ''
    if ($id -match 'cap|snapback|beanie|hat') { $clip = ', hideHair: true' }        # covers the head: no hair under it
    elseif ($id -match 'tattoo|chain') { $clip = ", under: 'brada'" }            # a long beard falls over it
    elseif ($id -match 'earring') { $clip = ", under: 'ucesy'" }                 # dreads and twists cover it
    "    { id: '$id', name: '$label', src: '$(& $rel $_)'$clip },"
  }
  [void]$out.AppendLine("  { id: '$($p.id)', name: '$($p.name)', optional: $($p.optional.ToString().ToLower()), items: [")
  $items | ForEach-Object { [void]$out.AppendLine($_) }
  [void]$out.AppendLine('  ] },')
}
[void]$out.AppendLine('];')
[IO.File]::WriteAllText((Join-Path $root 'js\looks.js'), $out.ToString(), $enc)
'looks.js: ' + ((Get-ChildItem $dir -Recurse -File -Filter '*.png').Count) + ' png'
